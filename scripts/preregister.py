"""Turn the Phase 5 pilot into the pre-registration record.

    python scripts/summarize.py outputs/grid/pilot --out outputs/pilot.csv
    python scripts/preregister.py outputs/pilot_runs.csv --tune outputs/tune_runs.csv

It checks that every pre-registered threshold is above the minimum detectable effect, picks
the router's nu and h0 by validation NLL, and writes both into the marked section of
docs/prereg-v1.md. Freezing is a separate, deliberate step taken by the project owner after
reading that file: commit it, then `git tag prereg-v1`. Only then may stage=final runs start.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
from omegaconf import OmegaConf

from labeltriage.data.splits import splits_dir
from labeltriage.eval.prereg import mde_report


def only(runs: pd.DataFrame, experiments: tuple[str, ...]) -> pd.DataFrame:
    """Keep the rows of the named experiments. Every sweep writes into one grid folder, so the
    summary CSV also holds gate and main-grid runs that must not enter the pilot statistics."""
    if "experiment" not in runs:
        return runs
    return runs[runs["experiment"].isin(experiments)]


def pick_router(tune: pd.DataFrame) -> dict[str, float]:
    """(nu, h0) with the lowest mean val NLL across the tuning settings."""
    best = tune.groupby(["method.nu", "method.h0"])["val/nll"].mean().idxmin()
    return {"nu": float(best[0]), "h0": float(best[1])}


BEGIN, END = "<!-- detectability:begin -->", "<!-- detectability:end -->"


def write_section(path: Path, body: str) -> None:
    """Replace the text between the detectability markers, leaving the rest of the file alone."""
    text = path.read_text(encoding="utf8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{path} has no {BEGIN} ... {END} section to fill")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    path.write_text(f"{head}{BEGIN}\n{body}\n{END}{tail}", encoding="utf8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pilot_runs", help="per-run CSV from scripts/summarize.py")
    parser.add_argument("--tune", help="per-run CSV of the router-tuning sweep (needs nu, h0)")
    parser.add_argument("--out", default="docs/prereg-v1.md")
    args = parser.parse_args(argv)

    hyp = OmegaConf.to_container(OmegaConf.load(splits_dir().parent / "prereg" / "hypotheses.yaml"))
    runs = only(pd.read_csv(args.pilot_runs), ("pilot", "t1_s3_pilot"))
    report = mde_report(runs, hyp)
    router = pick_router(only(pd.read_csv(args.tune), ("tune_router",))) if args.tune else None

    lines = [
        "Generated by `scripts/preregister.py` from the pilot.",
        "",
        "| Hypothesis | Seed SD | MDE | Threshold | Detectable |",
        "|---|---|---|---|---|",
    ]
    for h in ("H1", "H2", "H3", "H4"):
        if f"{h}/mde" in report:
            lines.append(
                f"| {h} | {report[f'{h}/seed_sd']:.4f} | {report[f'{h}/mde']:.4f} | "
                f"{report[f'{h}/threshold']:.4f} | {'yes' if report[f'{h}/detectable'] else 'NO'} |"
            )
    verdict = "pass" if report["gate/all_detectable"] else "FAIL"
    lines += ["", f"Gate (every threshold above its MDE): **{verdict}**"]
    if router:
        lines += [
            "",
            "Router settings (chosen by validation NLL):",
            "",
            f"- nu = {router['nu']}",
            f"- h0 = {router['h0']}",
        ]
    write_section(Path(args.out), "\n".join(lines))
    print("\n".join(lines))
    return 0 if report["gate/all_detectable"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
